-- Tabla de historial diario de ventas por producto
-- Agrupa las ventas de detalle_venta con la fecha de cada venta
-- para alimentar los modelos de IA (regresión, clasificación, búsqueda)

CREATE TABLE IF NOT EXISTS ventas_diarias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL REFERENCES productos (id) ON DELETE CASCADE,
    fecha DATE NOT NULL,
    cantidad_vendida INTEGER NOT NULL DEFAULT 0,
    total_ingreso NUMERIC(10, 2) NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS ix_ventas_diarias_producto_fecha
    ON ventas_diarias (producto_id, fecha DESC);

CREATE INDEX IF NOT EXISTS ix_ventas_diarias_fecha
    ON ventas_diarias (fecha DESC);

-- Poblar con datos históricos desde detalle_venta y ventas
INSERT INTO ventas_diarias (producto_id, fecha, cantidad_vendida, total_ingreso)
SELECT
    dv.producto_id,
    v.fecha::DATE AS fecha,
    SUM(dv.cantidad) AS cantidad_vendida,
    SUM(dv.subtotal) AS total_ingreso
FROM detalle_venta dv
JOIN ventas v ON dv.venta_id = v.id
GROUP BY dv.producto_id, v.fecha::DATE
ON CONFLICT DO NOTHING;
