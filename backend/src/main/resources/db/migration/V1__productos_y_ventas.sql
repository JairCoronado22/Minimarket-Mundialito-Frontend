    ON productos (codigo_barras)
    WHERE codigo_barras IS NOT NULL;

CREATE TABLE IF NOT EXISTS ventas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha TIMESTAMPTZ NOT NULL,
    cajero VARCHAR(120) NOT NULL,
    terminal VARCHAR(80) NOT NULL,
    medio_pago VARCHAR(30) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0)
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id INTEGER NOT NULL REFERENCES ventas (id) ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos (id) ON DELETE RESTRICT,
    nombre_producto VARCHAR(160) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT uq_detalle_venta_producto UNIQUE (venta_id, producto_id)
);

CREATE INDEX IF NOT EXISTS ix_ventas_fecha ON ventas (fecha DESC);

